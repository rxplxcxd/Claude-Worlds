def I(id, x, y, **kw):
    e = {'item': id, 'at': [x, y]}
    e.update(kw)
    return e


def W(id, x, h, row=None, **kw):
    e = {'item': id, 'wall': [x, h]}
    if row is not None:
        e['row'] = row
    e.update(kw)
    return e


def L(id, x, y, lift, **kw):
    e = {'item': id, 'at': [x, y], 'lift': lift}
    e.update(kw)
    return e


def room(name, rect, floor, wall):
    return {'name': name, 'rect': rect, 'floor': floor, 'wall': wall}


def P(a, b, openings=None, doors=None):
    p = {'from': a, 'to': b}
    if openings:
        p['openings'] = openings
    if doors:
        p['doors'] = doors
    return p


