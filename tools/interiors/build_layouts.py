# ------------------------------------------------------------------ Concordium (own art only)
def arcs(cx, cy, radii, a0, a1, item, gap, step=2.7):
    out = []
    for r in radii:
        n = max(1, int(r * math.radians(a1 - a0) / step))
        for k in range(n + 1):
            a = math.radians(a0 + (a1 - a0) * k / n)
            x = cx + r * math.cos(a) - 1.1
            y = cy + r * math.sin(a) - 0.8
            if abs(x + 1.1 - cx) < gap:
                continue
            out.append(I(item, round(x, 2), round(y, 2), action='sit'))
    return out


