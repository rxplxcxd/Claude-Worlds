"""Writes data/interiors/layouts.json – every enterable interior of WORLDS in
the interior standard (docs/INTERIOR_STANDARD.md): straight 3/4 view,
rectangular rooms, coordinates in floor tiles (x → right, y → south).
  I(id, x, y)          standing piece, footprint top-left at (x, y)
  W(id, x, h, row=)    on the back wall (or the inner wall at `row`), bottom
                       edge h tiles above the floor
  L(id, x, y, lift)    small thing on top of furniture (lift in art px)
Lists of ids are variants (picked per building by seed), min_wealth /
max_wealth keep pieces for richer / poorer settlements.
Run: python3 tools/interiors/build_layouts.py
"""
